def normalize_language(language: str | None) -> str:
    return "en" if (language or "").lower().startswith("en") else "es"


def tr(language: str | None, key: str, **values: object) -> str:
    language = normalize_language(language)
    text = TRANSLATIONS[language][key]
    return text.format(**values) if values else text


def format_number(value: float | Decimal, language: str | None, decimals: int = 2) -> str:
    """Format numbers with Spanish or English grouping without changing value."""
    language = normalize_language(language)
    formatted = f"{Decimal(str(value)):,.{decimals}f}"
    if language == "es":
        formatted = formatted.replace(",", "\0").replace(".", ",").replace("\0", ".")
    return formatted


def excel_number_format(language: str | None, decimals: int, currency: str | None = None) -> str:
    """Use Excel locale tags so the workbook displays separators by language."""
    language = normalize_language(language)
    locale_id = "0C0A" if language == "es" else "0409"
    precision = "0" * decimals
    prefix = f"[$-{locale_id}]"
    if currency == "USD":
        prefix = f"[$$-{locale_id}]"
    body = f"#,##0.{precision}"
    if currency == "Bs":
        body += ' "Bs"'
    return prefix + body
